#!/usr/bin/env python3
"""Write one plain, self-contained batch file per YouTube channel.

data/youtube/batch/bounce-theory.md and data/youtube/batch/ambient-escape.md are
what a "make today's batch" chat reads. They sit at fixed public URLs:
  https://raw.githubusercontent.com/omarjaradat2006-sudo/agent-hq/main/data/youtube/batch/<channel>.md
so any Claude chat can fetch them, with or without the skill loaded.

Run by the Footage fetcher workflow after every lineup push and clip download.
"""
import json, os, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATE = os.path.join(ROOT, "data", "youtube", "state.json")
OUT = os.path.join(ROOT, "data", "youtube", "batch")
REPO = os.environ.get("GITHUB_REPOSITORY", "omarjaradat2006-sudo/agent-hq")
RAW = f"https://raw.githubusercontent.com/{REPO}/main/data/youtube"
SLUG = {"Bounce Theory": "bounce-theory", "Ambient Escape": "ambient-escape"}
SKILL = {"Bounce Theory": "bounce-theory-videos", "Ambient Escape": "ambient-escape-videos"}


def esc(s):
    return str(s or "").replace("|", "/").replace("\n", " ").strip()


def brief(ch, items, s):
    date = (s.get("lineup") or {}).get("date") or "unknown"
    foot = {f.get("file"): f for f in s.get("footage") or [] if f.get("file")}
    ideas = {i.get("id"): i for i in s.get("ideas") or []}
    out = []
    out.append(f"# {ch}: today's batch ({date})")
    out.append("")
    out.append(f"Planned by Omar's Agent HQ YouTube team. Omar approves everything, so make exactly these {len(items)} videos, in this order, with these titles. Use the `{SKILL[ch]}` skill for how to render, folders, upload sheet and scheduling.")
    out.append("")
    out.append("Full data (ideas, footage, review): " + f"{RAW}/state.json")
    out.append("")
    out.append("## Hard rules")
    if ch == "Ambient Escape":
        out.append("1. **Long videos use the REAL downloaded clips below. Never draw, render or AI-generate a background scene for a slot whose clip says READY.** Download each clip from its link, check it with ffprobe, and list the downloaded files to Omar before rendering anything.")
        out.append("2. A generated or existing scene is only allowed for a slot whose clip is MISSING, and the finish message must name those slots.")
        out.append("3. Audio: copyright-safe only (synthesized rain/noise/fire/wind or CC0). Never reciter recordings, never Omar's voice. Put each clip's credit line in its video description.")
        out.append("4. Religious content must be accurate: ayat with surah:ayah, only authentic hadith with collection and number, double-check quiz answers.")
    else:
        out.append("1. Everything is generated by the Bounce Engine (sims.py). No stock footage on this channel.")
        out.append("2. Build every `★ NEW` slot as a new sims.py function from its spec below.")
        out.append("3. **Every slot's \"Today's twist\" is mandatory and must be VISIBLE.** The twist (frame shape, colours, ball count, rule change, melody, timer, two-ball race...) is what makes each video different. If the existing sims.py function can't do the twist, add a parameter or a new function. Never re-render a format with its default settings, never reuse a seed, colour pair or melody from the last 7 days, and never re-upload an older render.")
        out.append("4. **Check before delivering:** make a contact sheet of every new video next to the matching format's most recent upload (Upload Tool logs). If two look the same at a glance, redo that one. Tell Omar in one line per video what is visibly new.")
        out.append("5. Variety: at least 8 formats, no format more than twice among the Shorts (the lineup already follows this).")
    out.append(f"{5 if ch == 'Ambient Escape' else 6}. Nothing is uploaded or scheduled until Omar says \"go\".")
    out.append("")
    out.append("## The videos")
    out.append("")
    out.append("Most of these are remixes of videos that already won. Keep each winner's recipe (format, hook, length, pacing) and change only the twist.")
    out.append("")
    out.append("| Slot | Kind | Title | Format | Based on | Today's twist | Clip |")
    out.append("|---|---|---|---|---|---|---|")
    for v in items:
        clip = ""
        if v.get("footage"):
            f = foot.get(v["footage"], {})
            st = f.get("status", "wanted")
            clip = f"`{v['footage']}` " + ("READY" if st == "ready" else "MISSING (" + st + ")")
        new = " ★ NEW" if v.get("newIdea") else ""
        out.append(f"| {esc(v.get('slot'))} | {esc(v.get('kind'))} | {esc(v.get('title'))} | {esc(v.get('format'))}{new} | {esc(v.get('basis'))} | {esc(v.get('note'))} | {clip} |")
    out.append("")

    used = []
    for v in items:
        if v.get("footage") and v["footage"] not in used:
            used.append(v["footage"])
    # Clips the team requested for a slot even if the lineup row names another
    # one (e.g. an interlude clip for a long video).
    if ch == "Ambient Escape":
        for f in s.get("footage") or []:
            if f.get("file") and f["file"] not in used:
                used.append(f["file"])
    if used:
        out.append("## Clips to download first")
        out.append("")
        for name in used:
            f = foot.get(name, {})
            slots = ", ".join(v.get("slot", "") for v in items if v.get("footage") == name) or str(f.get("for") or "extra")
            if f.get("status") == "ready" and f.get("url"):
                meta = " · ".join(x for x in [f.get("size") if f.get("size") and not str(f.get("size")).startswith("0x") else "", f"{f['seconds']}s" if f.get("seconds") else "", f"{f['mb']} MB" if f.get("mb") else ""] if x)
                out.append(f"- **{name}** for {slots}: READY ({meta})")
                out.append(f"  - Download: `curl -L -o \"{name}\" \"{f['url']}\"`")
                if f.get("credit"):
                    out.append(f"  - Description credit: {f['credit']}")
            else:
                out.append(f"- **{name}** for {slots}: MISSING ({f.get('status', 'not requested')}). Use another READY clip that fits, or an existing scene, and say so.")
        out.append("")

    new_ids = [v.get("newIdea") for v in items if v.get("newIdea")]
    specs = [ideas[i] for i in dict.fromkeys(new_ids) if i in ideas]
    if specs:
        out.append("## Build specs for the new concepts")
        out.append("")
        for i in specs:
            out.append(f"### {i.get('title', '')}  (`{i.get('id')}`)")
            if i.get("format"):
                out.append(f"*{i['format']}*")
            out.append("")
            out.append(str(i.get("script") or "").strip())
            out.append("")

    out.append("## When the batch is done")
    out.append(f"- Tell Omar which clip each video used (by file name) and any slot that fell back.")
    out.append(f"- If this session can push to {REPO}: set `made: true` on each lineup item made and `status: \"filmed\"` on each used idea in data/youtube/state.json, then commit and push. Otherwise list the idea ids so Omar can press \"Mark made\" on the site.")
    out.append("")
    out.append(f"_Generated {datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}_")
    return "\n".join(out) + "\n"


def main():
    if not os.path.exists(STATE):
        return
    s = json.load(open(STATE))
    chans = ((s.get("lineup") or {}).get("channels")) or {}
    os.makedirs(OUT, exist_ok=True)
    for ch, items in chans.items():
        if ch in SLUG and items:
            with open(os.path.join(OUT, SLUG[ch] + ".md"), "w") as fh:
                fh.write(brief(ch, items, s))
            print("wrote", SLUG[ch])


if __name__ == "__main__":
    main()
